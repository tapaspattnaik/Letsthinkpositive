export function BottomNav() {
  const pathname  = usePathname()
  const { data: session } = useSession()

  function isActive(href: string) {
    if (href === '/') return pathname === '/'
    return pathname.startsWith(href)
  }

  return (
    /* Only visible on mobile — hidden on lg+ where the top navbar takes over */
    <nav className="lg:hidden fixed bottom-0 left-0 right-0 z-50 bg-white border-t border-teal-light/60 shadow-[0_-4px_20px_rgba(26,107,107,0.08)]"
      style={{ paddingBottom: 'env(safe-area-inset-bottom)' }}>
      <div className="flex items-stretch h-[60px]">
        {TABS.map(tab => {
          if (tab.authRequired && !session) return null
          const active = isActive(tab.href)
          return (
            <Link
              key={tab.href}
              href={tab.href}
              className={`flex-1 flex flex-col items-center justify-center gap-0.5 no-underline transition-colors active:scale-95 active:opacity-70
                ${active ? 'text-teal-deep' : 'text-text-xlight'}`}
              style={{ WebkitTapHighlightColor: 'transparent' }}>
              {tab.icon(active)}
              <span className={`text-[0.58rem] font-semibold leading-none tracking-wide
                ${active ? 'text-teal-deep' : 'text-text-xlight'}`}>
                {tab.label}
              </span>
              {active && (
                <span className="absolute bottom-0 w-5 h-0.5 bg-teal-deep rounded-full" />
              )}
            </Link>
          )
        })}

        {/* Sign In tab when logged out */}
        {!session && (
          <Link href="/login"
            className="flex-1 flex flex-col items-center justify-center gap-0.5 no-underline text-text-xlight"
            style={{ WebkitTapHighlightColor: 'transparent' }}>
            <svg className="w-6 h-6" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.8}>
              <path strokeLinecap="round" strokeLinejoin="round"
                d="M15.75 6a3.75 3.75 0 11-7.5 0 3.75 3.75 0 017.5 0zM4.501 20.118a7.5 7.5 0 0114.998 0A17.933 17.933 0 0112 21.75c-2.676 0-5.216-.584-7.499-1.632z" />
            </svg>
            <span className="text-[0.58rem] font-semibold leading-none tracking-wide">Sign In</span>
          </Link>
        )}
      </div>
    </nav>
  )
}
